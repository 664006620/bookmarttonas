#!/bin/sh
# ============================================================
# 保存网址到 NAS —— 开机启动脚本（非开发者只需改第 4 行密码）
# 用法：在 NAS 的「任务计划」里，让它在开机时运行本文件即可
# ============================================================

# ↓↓↓ 只改这一行：把引号里的换成你自己的强密码 ↓↓↓
export TOKEN="你的强密码"
# ↑↑↑ 只改这一行 ↑↑↑

export PORT=8000
DIR=$(dirname "$0")
cd "$DIR" || exit 1

# 以后台方式启动，并把日志写到同目录的 server.log
nohup python3 "$DIR/server.py" > "$DIR/server.log" 2>&1 &

echo "save-url 服务已启动，日志文件：$DIR/server.log"
